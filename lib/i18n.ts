const DICTS: Record<Locale, Dict> = { en, it };

/** Locale: explicit cookie > browser language > English. */
export async function getLocale(): Promise<Locale> {
  const c = (await cookies()).get("locale")?.value;
  if (c === "en" || c === "it") return c;
  const accept = (await headers()).get("accept-language") ?? "";
  return accept.toLowerCase().startsWith("it") ? "it" : "en";
}

export async function getT() {
  const locale = await getLocale();
  return { locale, t: DICTS[locale] };
}

export function timeAgo(iso: string | null, locale: Locale, t: Dict) {
  if (!iso) return t.never;
  const s = Math.max(0, (Date.now() - Date.parse(iso)) / 1000);
  const rtf = new Intl.RelativeTimeFormat(locale, { numeric: "auto", style: "short" });
  if (s < 60) return rtf.format(-Math.round(s), "second");
  if (s < 3600) return rtf.format(-Math.round(s / 60), "minute");
  if (s < 86400) return rtf.format(-Math.round(s / 3600), "hour");
  return rtf.format(-Math.round(s / 86400), "day");
}
